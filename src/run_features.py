import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, str(Path(__file__).parent))
from cleaning import clean_all  # noqa: E402
from features import FEATURE_DOC, TRAIN_END, build_all  # noqa: E402
from load_data import load_data_tables  # noqa: E402

OUT = Path("data/features")
REPORT = Path("reports/feature_report.md")


def md_table(df):
    head = "| " + " | ".join(df.columns) + " |\n|" + "|".join("---" for _ in df.columns) + "|\n"
    return head + "\n".join("| " + " | ".join(str(v).replace("|", "/") for v in r) + " |" for r in df.itertuples(index=False))


def demand_signal(d):
    """Spearman correlation of each demand feature with units_sold, plus naive forecasts on the 2026 test months."""
    d = d[d["has_full_history"]]
    cols = ["units_lag1", "units_lag3", "units_lag12", "units_roll_mean_3", "units_roll_mean_12", "seasonal_index",
            "total_units_lag1", "promo_lag1", "time_index"]
    rows = []
    for c in cols:
        r = stats.spearmanr(d[c], d["units_sold"])
        rows.append([c, f"{r.statistic:.2f}", "<0.001" if r.pvalue < 0.001 else f"{r.pvalue:.3f}"])
    corr = pd.DataFrame(rows, columns=["Feature", "Spearman rho with units sold", "p"])

    train, test = d[d["month"] <= TRAIN_END], d[d["month"] > TRAIN_END]
    prod_mean = test["product_id"].map(train.groupby("product_id")["units_sold"].mean())
    mae = lambda pred: float(np.abs(test["units_sold"] - pred).mean())
    base = pd.DataFrame([
        ["Product's average of 2023-2025", mae(prod_mean)],
        ["Product's average x seasonal index", mae(prod_mean * (1 + test["seasonal_index"] / 100))],
        ["Same as last month (lag 1)", mae(test["units_lag1"])],
        ["Same as last year (lag 12)", mae(test["units_lag12"])],
        ["Average of last 3 months", mae(test["units_roll_mean_3"])],
        ["Average of last 12 months", mae(test["units_roll_mean_12"])],
    ], columns=["Naive forecast for 2026", "Average error (units)"]).sort_values("Average error (units)")
    base["Average error (units)"] = base["Average error (units)"].map(lambda v: f"{v:,.0f}")
    return corr, base, len(test), float(test["units_sold"].mean())


def qc_signal(q):
    """Which QC features separate Review from Pass? Split into 'known after the test' and 'known BEFORE the test'."""
    y = q["is_review"].astype(float)
    after = ["ph_value", "abs_abv_deviation", "abv_deviation", "temperature_c", "specific_gravity", "colour_ebc", "defects_per_1000L", "defect_units"]
    before = ["planned_volume_litre", "yield_rate", "loss_pct", "cost_per_litre", "shift_count", "month_no", "days_since_prev_batch_line",
              "prev_batch_review_line", "review_rate_prev10_line", "prev_yield_line", "yield_roll5_prev_line"]

    def table(cols):
        rows = []
        for c in cols:
            m = q[c].notna()
            r = stats.pointbiserialr(y[m], q.loc[m, c])
            rows.append([c, round(float(r.statistic), 3), float(r.pvalue)])
        return pd.DataFrame(rows, columns=["Feature", "r with Review", "p"]).sort_values("p")

    ta, tb = table(after), table(before)
    fmt = lambda t: t.assign(p=t["p"].map(lambda v: "<0.001" if v < 0.001 else f"{v:.3f}"))
    return fmt(ta), fmt(tb), int((tb["p"] < 0.05).sum()), len(tb)


def main():
    clean, *_ = clean_all(load_data_tables())
    F = build_all(clean)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, df in F.items():
        df.to_csv(OUT / f"{name}.csv", index=False, date_format="%Y-%m-%d")
    print(f"Saved {len(F)} feature tables to {OUT}/")

    overview = pd.DataFrame([[n, len(df), df.shape[1], f"{df.isna().any(axis=1).mean():.0%}"] for n, df in F.items()],
                            columns=["Table", "Rows", "Columns", "Rows with a blank"])
    corr, base, n_test, test_mean = demand_signal(F["demand_features"])
    qa, qb, n_sig_before, n_before = qc_signal(F["qc_features"])
    doc = pd.DataFrame(FEATURE_DOC, columns=["Table", "Feature", "Meaning", "Uses only"])

    L = [
        "# Feature Engineering Report", "",
        "_Generated by `python src/run_features.py`. Code: `src/features.py`; tests: `src/test_features.py`._", "",
        "## 1. Feature tables", md_table(overview), "",
        "Blanks are expected and meaningful: a lag has no value in the first months, a product-month with no production batch has no yield. "
        "Models must either drop those rows (`has_full_history`) or fill them using **training rows only**.", "",
        "## 2. The leakage rule",
        "A feature for time t may use only information known **before** t. Lags and rolling windows are shifted by one period, and the seasonal index is learned "
        "from 2023-2025 only. `python src/test_features.py` proves this by changing the future on purpose and checking that earlier features do not move.", "",
        "## 3. What each feature means", md_table(doc), "",
        "## 4. Do the demand features carry signal?",
        f"Spearman correlation with `units_sold` (product-months with 12 months of history, n = {int(F['demand_features']['has_full_history'].sum())}):", "", md_table(corr), "",
        f"Naive forecasts for the {n_test} product-months of 2026 (average actual demand {test_mean:,.0f} units). **Any model must beat the first row:**", "", md_table(base), "",
        "Lag features (last month, last year, recent averages) carry almost no information: product demand behaves like noise around a product average, with only the "
        "calendar pattern and total-market level adding a little.", "",
        "## 5. Do the QC features carry signal?",
        "**Known only AFTER the lab test** (these define the Review decision):", "", md_table(qa), "",
        f"**Known BEFORE the lab test** (usable for an early warning). {n_sig_before} of {n_before} are significant at 5%, "
        f"and with {n_before} tests about {n_before * 0.05:.1f} would appear by chance alone:", "", md_table(qb), "",
        "`abs_abv_deviation` is the engineered feature that exposes the specification rule (Review when pH is outside 4.1-5.0 or the ABV gap is above 0.30). "
        "Classifying Review from after-test measurements will therefore be near-perfect, but it only rediscovers that rule.", "",
        "## 6. How these tables are used in Step 8",
        "- `demand_features`: regression (compare against the product-average baseline).",
        "- `qc_features`: classification, as two separate problems (after-test: rediscover the rule; before-test: early warning).",
        "- `customer_features`: clustering (RFM segments).",
        "- `product_month_features` and `supplier_features`: profitability analysis and anomaly detection.",
    ]
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"Report written: {REPORT}")


if __name__ == "__main__":
    main()
