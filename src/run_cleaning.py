"""
run_cleaning.py  -  STEP 6d: Run the whole cleaning pipeline.

Run from the project folder:   python src/run_cleaning.py

It will:
    1. load the raw Excel tables
    2. clean them (cleaning.py)
    3. save the cleaned tables as CSV files in data/processed/
    4. write reports/cleaning_report.md  (what changed and why)
    5. try the encoding/scaling step (preprocess.py)
"""

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from cleaning import clean_all, season_from_month  # noqa: E402
from load_data import load_data_tables  # noqa: E402

OUT_DIR = Path("data/processed")
REPORT = Path("reports/cleaning_report.md")


def md_table(df):
    head = "| " + " | ".join(df.columns) + " |\n|" + "|".join("---" for _ in df.columns) + "|\n"
    rows = "\n".join("| " + " | ".join(str(v).replace("|", "/") for v in r) + " |" for r in df.itertuples(index=False))
    return head + rows


def before_after(raw, clean):
    """Numbers that show the business fixes worked."""
    so_raw = raw["Sales_Orders"].merge(raw["Customers"], on="customer_id")
    so_new = clean["Sales_Orders"].merge(clean["Customers"], on="customer_id")
    meteo = season_from_month(raw["Demand_History"]["month"].dt.month)
    sup = clean["Suppliers"]
    return pd.DataFrame([
        ["Orders placed before the customer's first_order_date",
         f"{(so_raw['order_date'] < so_raw['first_order_date']).mean():.1%}",
         f"{(so_new['order_date'] < so_new['first_order_date']).mean():.1%}"],
        ["Demand_History rows whose season matches the month",
         f"{(raw['Demand_History']['season'] == meteo).mean():.1%}", "100.0%"],
        ["Average supplier on-time rate",
         f"{sup['on_time_rate_stated'].mean():.1%} (stated)", f"{sup['on_time_rate_calc'].mean():.1%} (calculated)"],
        ["Demand_History rows that are after the data cutoff (Nov-Dec 2026)",
         "mixed in with real history", f"{int(clean['demand']['is_forecast_period'].sum())} flagged, excluded from training"],
        ["Cancelled orders in revenue", "included unless filtered by hand",
         f"{int(clean['Sales_Orders']['is_cancelled'].sum())} flagged; net_sales_counted_eur = 0 for them"],
    ], columns=["Check", "Before", "After"])


def main():
    raw = load_data_tables()
    clean, log, outliers, checks = clean_all(raw)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, df in clean.items():
        df.to_csv(OUT_DIR / f"{name}.csv", index=False, date_format="%Y-%m-%d")
    print(f"Saved {len(clean)} cleaned tables to {OUT_DIR}/")

    ba = before_after(raw, clean)
    kept = {n: (len(raw[n]), len(clean[n])) for n in raw}
    rows_lost = sum(a - b for a, b in kept.values())

    prep_text = ""
    try:
        from preprocess import DEMAND_PROBLEM, QC_PROBLEM, prepare
        parts = []
        for label, prob in [("QC status (classification)", QC_PROBLEM), ("Monthly demand (regression)", DEMAND_PROBLEM)]:
            r = prepare(clean, prob)
            parts.append([label, f"{len(r['X_train'])} / {len(r['X_test'])}", len(r["feature_names"]),
                          f"{abs(r['X_train'].iloc[:, :len(prob['numeric'])].mean().mean()):.3f}"])
        prep_text = md_table(pd.DataFrame(parts, columns=["Problem", "Train / test rows", "Features after encoding", "Mean of scaled train numbers"]))
        print("Encoding and scaling: OK")
    except (ImportError, OSError) as e:
        prep_text = f"_scikit-learn could not be loaded here ({e}); cleaning above is unaffected._"
        print("Encoding and scaling skipped:", e)

    generic = log[log["step"] != "business rule"]
    generic_text = "; ".join(f"{r.table}: {r.detail} ({r.count} rows)" for r in generic.itertuples()) or "nothing"
    lines = [
        "# Data Cleaning Report", "",
        "_Generated by `python src/run_cleaning.py`. Code: `src/cleaning.py`, `src/preprocess.py`._", "",
        "## 1. Summary",
        f"- {len(raw)} raw tables cleaned; **{rows_lost} rows removed** in total "
        "(no duplicates, blank primary keys or unreadable values were found in the raw file).",
        "- The raw Excel file is never modified; cleaned copies are written to `data/processed/` (not uploaded to GitHub).",
        "- Outliers are **flagged, never deleted**: each flagged value lies inside a possible range (for example flagged yields are 75% to 96%), so none looks like an error.",
        f"- {sum(p for _, p in checks)} of {len(checks)} post-cleaning checks passed.", "",
        "## 2. The business fixes (before and after)", md_table(ba), "",
        "## 3. Every action the pipeline took", md_table(log[["table", "step", "detail", "count"]]), "",
        "Type conversion, duplicate and missing-value steps log a line only when they change something. "
        f"On the raw file they changed: {generic_text}. `src/test_cleaning.py` proves they work on a deliberately messy copy.", "",
        "## 4. Outliers (IQR rule, judged within a group)",
        "A value is flagged if it is more than 1.5 x IQR outside the middle 50% **of its own group** "
        "(for example unit cost within the same material). Judging all rows together would wrongly flag expensive "
        "materials and large expense categories.", "",
        md_table(outliers[outliers["flagged"] > 0][["table", "column", "judged_within", "flagged", "share_pct", "rows"]]), "",
        f"{int((outliers['flagged'] == 0).sum())} of {len(outliers)} checked columns have no outliers.", "",
        "## 5. Post-cleaning checks", "\n".join(f"- {'PASS' if p else 'FAIL'}: {d}" for d, p in checks), "",
        "## 6. Encoding and scaling for machine learning", prep_text, "",
        "Train = 2023 to 2025, test = 2026 (split by date). Numbers are scaled and words one-hot encoded with values learned from the "
        "training rows only, to avoid data leakage.", "",
        "## 7. Decisions you should be able to explain",
        "1. **Blank numbers:** filled with the median of their group, plus a `*_was_missing` flag. (None occurred in the raw file.)",
        "2. **Outliers:** flagged, not removed, because the extremes are valid values in this data.",
        "3. **first_order_date and season:** rebuilt from the data, since the stated values contradict it. The stated values are kept as `*_stated`.",
        "4. **Supplier on-time rate:** the calculated rate is used; the stated one is kept for reference.",
        "5. **Cancelled orders:** kept but flagged, so counts of orders stay correct and revenue uses `net_sales_counted_eur`.",
        "6. **Nov-Dec 2026 demand rows:** flagged `is_forecast_period` and excluded from model training.",
    ]
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Report written: {REPORT}")
    print(f"Rows removed: {rows_lost} | checks passed: {sum(p for _, p in checks)}/{len(checks)}")


if __name__ == "__main__":
    main()
