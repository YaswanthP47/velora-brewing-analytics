"""
run_statistics.py  -  STEP 7c: Run the statistical analysis and write the report.

Run from the project folder:   python src/run_statistics.py

Writes:
    reports/statistics_results.csv      every hypothesis test
    reports/confidence_intervals.csv    every confidence interval
    reports/statistics_report.md        the written report (all numbers are filled in by the code)
"""

import calendar
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from cleaning import clean_all  # noqa: E402
from load_data import load_data_tables  # noqa: E402
from statistics_analysis import run_all  # noqa: E402

REPORT = Path("reports/statistics_report.md")


def fmt_p(p):
    return "<0.0001" if p < 0.0001 else f"{p:.4f}" if p < 0.001 else f"{p:.3f}"


def md_table(df):
    head = "| " + " | ".join(df.columns) + " |\n|" + "|".join("---" for _ in df.columns) + "|\n"
    return head + "\n".join("| " + " | ".join(str(v).replace("|", "/") for v in r) + " |" for r in df.itertuples(index=False))


def main():
    clean, *_ = clean_all(load_data_tables())
    cis, tests, x = run_all(clean)
    Path("reports").mkdir(exist_ok=True)
    tests.to_csv("reports/statistics_results.csv", index=False)
    cis.to_csv("reports/confidence_intervals.csv", index=False)

    T = lambda key: tests[tests["question"].str.contains(key, regex=False)].iloc[0]
    C = lambda key: cis[cis["quantity"] == key].iloc[0]
    def ci_txt(r, d=1, unit=""):
        """'88.6% (95% CI 88.1% to 89.1%)'  or  '0.17 (95% CI -0.22 to 0.57) points'"""
        pct = "%" if unit == "%" else ""
        tail = f" {unit}" if unit and unit != "%" else ""
        return f"{r.estimate:.{d}f}{pct} (95% CI {r.low:.{d}f}{pct} to {r.high:.{d}f}{pct}){tail}"

    yld, rev, late, mar = C("Average batch yield"), C("Batch review rate"), C("Share of late deliveries"), C("Gross margin (all products)")
    cancel, price, disc_m, disc_q = C("Share of cancelled orders"), C("Margin gain per +1 EUR wholesale price"), \
        C("Margin change per +1 point of discount"), C("Units per line change per +1 point of discount (non-Online)")
    trend = C("Demand trend per month (seasonally adjusted)")
    ctl, idx = x["control"], x["seasonal_index"]
    sales_ok = clean["sales_lines"][(~clean["sales_lines"]["is_cancelled"]) & (clean["sales_lines"]["sales_channel"] != "Online")]
    typical_units = sales_ok["quantity_units"].mean()
    sig = tests[tests["verdict"] == "Significant"]
    nom = tests[tests["verdict"] == "Nominal only"]
    prods = cis[cis["quantity"].str.startswith("Gross margin, ")].sort_values("estimate")
    low_p, high_p = prods.iloc[0], prods.iloc[-1]
    ph = T("pH")
    gp, pv_, sr = T("ABV gap"), T("previous batch"), x["spec_rule"]

    shown = tests[["id", "question", "method", "p_value", "p_holm", "effect_name", "effect", "verdict"]].copy()
    shown["p_value"], shown["p_holm"] = shown["p_value"].map(fmt_p), shown["p_holm"].map(fmt_p)
    shown["effect"] = shown["effect"].map(lambda v: f"{v:.3f}")
    shown.columns = ["ID", "Question", "Test", "p", "p (Holm)", "Effect measure", "Effect", "Verdict"]

    L = [
        "# Statistical Quality and Profitability Analysis", "",
        "_Week 6 deliverable. Generated by `python src/run_statistics.py`; every number below is filled in by the code. "
        "Code: `src/stats_utils.py`, `src/statistics_analysis.py`. Data: synthetic, cleaned by Step 6._", "",
        "## 1. How to read this report",
        "- **Confidence interval (CI):** a range that very likely holds the true value. A narrow CI means a precise estimate.",
        "- **p-value:** how surprising the data would be if there were no real effect. Small means surprising.",
        "- **Effect size:** how big the difference is. A tiny effect can still have a tiny p-value, so we always show both.",
        f"- **Multiple testing:** we ran {len(tests)} tests, so a few would look significant by luck alone. "
        "The **Holm correction** adjusts every p-value for this. **Significant** below means it survives that correction.", "",
        "## 2. Main results", "",
        f"**{len(sig)} of {len(tests)} tests are significant after correction:**",
        "\n".join(f"- {r.question} (adjusted p {'<0.0001' if r.p_holm < 0.0001 else '= ' + fmt_p(r.p_holm)}; {r.effect_name} = {r.effect:.2f})" + (f". {r.note}" if r.note else "") for r in sig.itertuples()),
        "", f"**{len(nom)} test is only nominally significant (not after correction):** "
        + "; ".join(f"{r.question} (p = {fmt_p(r.p_value)}, adjusted {fmt_p(r.p_holm)})" for r in nom.itertuples()) + ".",
        f"**The other {len(tests) - len(sig) - len(nom)} tests found no evidence of a difference.**", "",
        "## 3. Quality",
        f"- **Yield** averages {ci_txt(yld, 1, '%')}. Production lines, batch status and time trend show no differences "
        f"(p = {fmt_p(T('between production lines').p_value)}, {fmt_p(T('batch status').p_value)}, {fmt_p(T('drifting').p_value)}).",
        f"- Yield differs strongly **between products** (eta-squared = {T('between products').effect:.2f}), but this is expected because each product has its own target. "
        f"Against those targets the average gap is {ci_txt(C('Average yield minus product target'), 2, 'points')}, "
        f"which includes zero (p = {fmt_p(T('different from the product targets').p_value)}).",
        f"- **Control chart:** with limits from batch-to-batch variation, {ctl['outside']} of {len(ctl['series'])} batches fall outside "
        f"{ctl['lcl']:.1f}% to {min(ctl['ucl'], 100):.1f}% (the upper limit is capped at 100%), and the batch-to-batch correlation is {ctl['lag1_autocorr']:.2f}. "
        "The process is **statistically stable**: yield varies randomly around 88.6% with no signal to investigate.",
        f"- **Review rate** is {ci_txt(rev, 1, '%')}. By product and by line the differences are not significant "
        f"(p = {fmt_p(T('by product').p_value)} and {fmt_p(T('by production line').p_value)}), "
        f"but with only about 35 batches per product a test could detect only differences of about {x['min_detectable_review_diff'] * 100:.0f} points or more. "
        "So \"no significant difference\" here means **inconclusive for small differences**, not proof that products are equal.",
        f"- **Lab measurements need the right quantity.** Raw pH is only nominally different between Review and Pass batches (p = {fmt_p(ph.p_value)}, d = {ph.effect:.2f}, adjusted p = {fmt_p(ph.p_holm)}), "
        f"and the other raw values look the same, because errors in both directions cancel in averages. But the **ABV gap from the product's declared ABV** is much larger in Review batches "
        f"(d = {gp.effect:.2f}, p {'<0.0001' if gp.p_value < 0.0001 else '= ' + fmt_p(gp.p_value)}). The rule \"ABV gap above 0.30 or pH outside 4.1 to 5.0\" reproduces the real status for "
        f"**{sr['accuracy'] * 100:.1f}%** of batches ({sr['flagged']} flagged, {sr['review']} in Review; {sr['false_alarms']} false alarms, {sr['missed']} missed). "
        "The thresholds were found by looking at the data, so confirm them with the brewery.",
        f"- **Early warning is weak:** a batch is not more likely to be Review because the previous batch on its line was (p = {fmt_p(pv_.p_value)}, Cramer's V = {pv_.effect:.2f}).", "",
        "## 4. Supply",
        f"- **{ci_txt(late, 1, '%')}** of deliveries are late.",
        f"- Supplier differences (p = {fmt_p(T('between suppliers').p_value)}) and the 2023 vs later improvement (p = {fmt_p(T('later in 2023').p_value)}) are **not significant**, "
        "so the EDA statement that lateness \"improved after 2023\" is not statistically supported.",
        f"- A supplier's stated on-time rate does not predict its real one (Spearman rho = {T('STATED').effect:.2f}, p = {fmt_p(T('STATED').p_value)}).", "",
        "## 5. Profitability",
        f"- **Gross margin** is {ci_txt(mar, 1, '%')} overall (bootstrap over orders). Product margins are very precise: "
        f"{low_p.quantity.replace('Gross margin, ', '')} {low_p.estimate:.1f}% (CI {low_p.low:.1f} to {low_p.high:.1f}) up to "
        f"{high_p.quantity.replace('Gross margin, ', '')} {high_p.estimate:.1f}% (CI {high_p.low:.1f} to {high_p.high:.1f}). These ranges do not overlap, so the gap is real.",
        f"- **Margin follows price:** each extra EUR 1 of wholesale price adds {ci_txt(price, 1, 'points')} of margin (r = {T('rise with price').effect:.2f}, "
        f"R-squared = {T('rise with price').effect ** 2:.2f}, based on 13 products).",
        f"- **Discounts cost margin:** each extra point of discount changes margin by {ci_txt(disc_m, 2, 'points')}. "
        "This is partly arithmetic (revenue falls while cost stays).",
        f"- **Discounts do not bring volume:** each extra point of discount changes units per line by {ci_txt(disc_q, 1, 'units')} (p = {fmt_p(T('bring bigger orders').p_value)}). "
        f"The upper end of the interval means a 10-point discount could raise a typical order (about {typical_units:.0f} units) by at most about {disc_q.high * 10 / typical_units * 100:.0f}%, "
        "far below the roughly 11% volume increase a 10% discount needs just to keep revenue level.",
        f"- Margin does not differ by sales channel (p = {fmt_p(T('by sales channel').p_value)}). Cancellations are {ci_txt(cancel, 1, '%')} with no difference by channel or year.", "",
        "## 6. Sales, seasonality and demand",
        f"- **Sales are flat:** Jan-Oct monthly sales do not differ between years (p = {fmt_p(T('Jan-Oct monthly sales').p_value)}) and show no trend over 46 months (p = {fmt_p(T('trending up or down').p_value)}).",
        f"- **Sales seasonality is inconclusive:** effect size {T('calendar month (seasonality)').effect:.2f} is large, but with 3 to 4 observations per calendar month the test cannot decide "
        f"(Kruskal p = {fmt_p(T('calendar month (seasonality)').p_value)}; {T('calendar month (seasonality)').note}).",
        f"- **Total demand is clearly seasonal:** after removing the trend, calendar month explains {x['seasonal_eta2'] * 100:.0f}% of the variation "
        f"(p = {fmt_p(T('differ by calendar month (after').p_value)}). Seasonal index (percent of an average month): "
        + ", ".join(f"{calendar.month_abbr[m]} {v:+.0f}%" for m, v in idx.items()) + ".",
        f"- **Demand is trending up:** {ci_txt(trend, 0, 'units')} more per month, month after month, seasonally adjusted (p = {fmt_p(T('trending up (seasonally').p_value)}). "
        f"A trend test without seasonal adjustment misses this (p = {x['naive_trend_p']:.2f}) because the seasonal swings hide it.",
        f"- **Individual products are too noisy to show it alone:** only {x['products_with_seasonality']} of {x['n_products']} products {'shows' if x['products_with_seasonality'] == 1 else 'show'} a significant calendar-month effect on their own, "
        f"and products move together very little (average correlation between product series {x['avg_product_corr']:.2f}). "
        f"Pooled across all product-months the seasonal pattern still correlates with units sold (rho = {T('individual product-months').effect:.2f}, p {'<0.0001' if T('individual product-months').p_value < 0.0001 else '= ' + fmt_p(T('individual product-months').p_value)}), so it is real but small per product.",
        f"- Promotions do not raise units sold (rho = {T('promotions').effect:.2f}, p = {fmt_p(T('promotions').p_value)}).", "",
        "## 7. What this means for the machine learning steps",
        "1. **QC status: two different problems.** (a) *Classifying* Review from the QC measurements will be almost perfect, because Review is a specification check; a model only rediscovers the rule, "
        "so always compare it with the two-line rule and say so in the report. (b) *Predicting Review before the test* from pre-test information (product, line, volume, previous batch outcomes) has little to learn from.",
        "2. **Product-level demand forecasts will be noisy.** Seasonality and trend are real in the total, but weak per product. Compare models against simple baselines (product average, seasonal index) before claiming improvement.",
        "3. **Useful features:** `abv_gap` and pH window for QC; calendar month (or seasonal index), a time trend and price tier for demand. Promotion discount adds little.",
        "4. **Do not model supplier or line differences** for yield or lateness; the data gives no evidence they exist.", "",
        "## 8. Refinements to earlier EDA statements",
        "- **Lab measurements (correction):** an earlier version of the EDA said the measurements do not explain Review. That was wrong: raw averages hide a specification rule that only appears once ABV is compared with the declared ABV (see section 3).",
        "- Lateness \"improved after 2023\" and supplier late shares \"range 43% to 67%\": these differences cannot be told apart from chance with about 60 deliveries per supplier (see section 4).",
        f"- Maintenance: preventive jobs had the longest average downtime, but the difference is not significant (p = {fmt_p(T('maintenance type').p_value)}).",
        f"- Sales seasonality: EDA said \"no stable seasonality\"; the test says inconclusive (p = {fmt_p(T('calendar month (seasonality)').p_value)}).", "",
        "## 9. Every test", md_table(shown), "",
        "Confidence intervals are in `reports/confidence_intervals.csv`.",
    ]
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{len(tests)} tests, {len(cis)} confidence intervals | significant after Holm: {len(sig)} | nominal only: {len(nom)}")
    print(f"Report written: {REPORT}")


if __name__ == "__main__":
    main()
